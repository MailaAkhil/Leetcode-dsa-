class Solution {
    public long countCommas(long n) {
        long ans=0;
        if(n<1000){
            ans=0;
        }
        else if(n<1000000){
            ans=n-999;
        }
        else if(n<1000000000L){
            ans=999999-999;
            ans+=(n-999999)*2;
        }
        else if(n<1000000000000L){
            ans=999999-999;
            ans+=(999999999-999999)*2;
            ans+=(n-999999999)*3;
        }
        else if(n<1000000000000000L){
            ans=999999-999;
            ans+=(999999999-999999)*2;
            ans+=(999999999999L-999999999)*3;
            ans+=(n-999999999999L)*4;
        }
        else{
            ans=999999-999;
            ans+=(999999999-999999)*2;
            ans+=(999999999999L-999999999)*3;
            ans+=(999999999999999L-999999999999L)*4;
            ans+=(n-999999999999999L)*5;
        }
        return ans;
    }
}